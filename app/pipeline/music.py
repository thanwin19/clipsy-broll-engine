"""Background music by mood: Openverse (commercial-use licences only) with a procedural fallback bed."""
from dataclasses import dataclass
from pathlib import Path

import httpx

from app.config import get_settings
from app.logs import get_logger
from app.pipeline import media

log = get_logger("music")

MOOD_QUERIES = {"upbeat": "upbeat acoustic", "calm": "calm ambient piano", "corporate": "corporate background",
                "inspiring": "inspiring cinematic", "sombre": "sad piano ambient", "playful": "playful ukulele"}
OK_LICENCES = {"cc0", "by", "pdm"}  # no NC, no ND, no SA


@dataclass
class Track:
    path: Path
    title: str
    source: str
    licence: str
    licence_url: str
    attribution: str
    page_url: str
    ai_generated: bool = False


def procedural_bed(dest: Path, seconds: float, mood: str) -> Track:
    """Soft synthesised pad (our own output, licence-clean). Used when music sources fail."""
    chords = {"sombre": (110, 130.81, 164.81), "calm": (130.81, 164.81, 196.0)}.get(mood, (146.83, 185.0, 220.0))
    srcs = []
    for f in chords:
        srcs += ["-f", "lavfi", "-i", f"sine=frequency={f}:duration={seconds + 1:.2f}"]
    n = len(chords)
    media.ffmpeg(*srcs, "-filter_complex",
                 "".join(f"[{i}:a]" for i in range(n)) + f"amix=inputs={n},volume=0.6,"
                 "tremolo=f=0.15:d=0.4,lowpass=f=900,afade=t=in:d=2,aecho=0.8:0.7:60:0.3[a]",
                 "-map", "[a]", "-ar", "48000", "-ac", "2", dest)
    return Track(dest, "Procedural ambient pad", "procedural", "Generated by this service (no third-party rights)",
                 "", "Generated by IncuBrix B-roll engine", "")


def find_music(mood: str, seconds: float, work: Path) -> tuple[Track | None, list[str]]:
    s = get_settings()
    warnings: list[str] = []
    if s.music_provider == "none":
        return None, warnings
    if s.music_provider == "openverse" and not s.is_disabled("openverse"):
        try:
            with httpx.Client(timeout=s.provider_timeout_seconds, follow_redirects=True,
                              headers={"User-Agent": "incubrix-broll-engine/1.0"}) as c:
                r = c.get("https://api.openverse.org/v1/audio/", params={
                    "q": MOOD_QUERIES.get(mood, "calm ambient"), "license_type": "commercial", "category": "music",
                    "page_size": 20, "mature": "false"})
                r.raise_for_status()
                results = r.json().get("results", [])
                results = [x for x in results if (x.get("license") or "").lower() in OK_LICENCES
                           and x.get("url") and (x.get("duration") or 0) >= 30000]
                results.sort(key=lambda x: abs((x.get("duration") or 0) / 1000 - seconds))
                for x in results[:3]:
                    try:
                        dest = work / f"music_{x['id']}.{x.get('filetype') or 'mp3'}"
                        resp = c.get(x["url"])
                        resp.raise_for_status()
                        dest.write_bytes(resp.content)
                        if not media.has_audio(dest):
                            raise ValueError("no audio stream")
                        lic = f"CC {x['license'].upper()} {x.get('license_version') or ''}".strip()
                        return Track(dest, x.get("title", ""), f"openverse/{x.get('source')}", lic,
                                     x.get("license_url", ""), f"\"{x.get('title')}\" by {x.get('creator')} ({lic})",
                                     x.get("foreign_landing_url", "")), warnings
                    except Exception as e:
                        log.warning("music download failed: %s", e)
        except Exception as e:
            warnings.append(f"MUSIC_SOURCE_DOWN: Openverse unavailable ({type(e).__name__}); procedural bed used")
    try:
        return procedural_bed(work / "music_bed.wav", seconds, mood), warnings
    except Exception as e:
        warnings.append(f"NO_MUSIC: music fallback failed ({type(e).__name__})")
        return None, warnings
