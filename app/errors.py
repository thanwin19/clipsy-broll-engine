"""JSON errors: {"error": {"code", "message", "retryable", "details"}}. Codes listed in README."""
from fastapi import Request
from fastapi.exceptions import RequestValidationError
from fastapi.responses import JSONResponse
from starlette.exceptions import HTTPException as StarletteHTTPException

# code -> (http status, retryable, description)
ERROR_CODES: dict[str, tuple[int, bool, str]] = {
    "VALIDATION_ERROR": (422, False, "Request body or parameters are invalid."),
    "NO_INPUT": (422, False, "None of audio_url, audio upload, script or scenes was given."),
    "EMPTY_SCRIPT": (422, False, "The script (or every scene text) is empty."),
    "SCRIPT_TOO_LONG": (422, False, "The script exceeds MAX_SCRIPT_CHARS."),
    "UNSUPPORTED_FILE_TYPE": (415, False, "Audio must be mp3, wav or m4a."),
    "FILE_TOO_LARGE": (413, False, "Upload exceeds MAX_UPLOAD_MB."),
    "AUDIO_TOO_LONG": (422, False, "Audio is longer than MAX_AUDIO_SECONDS (10 minutes)."),
    "AUDIO_UNREADABLE": (422, False, "The audio file is corrupt or cannot be decoded."),
    "NO_SPEECH_DETECTED": (422, False, "The audio is silent or contains music only; no narration found."),
    "INPUT_DOWNLOAD_FAILED": (502, True, "The audio_url could not be downloaded."),
    "INVALID_ASPECT_RATIO": (422, False, "Aspect ratios must be from 16:9, 9:16, 1:1."),
    "IDEMPOTENCY_CONFLICT": (409, False, "Idempotency-Key was reused with a different request body."),
    "JOB_NOT_FOUND": (404, False, "No job with this id."),
    "SCENE_NOT_FOUND": (404, False, "No scene with this index in the job."),
    "JOB_NOT_READY": (409, True, "The job has not finished yet."),
    "UNAUTHORIZED": (401, False, "Missing or wrong bearer token."),
    "RATE_LIMITED": (429, True, "Too many requests; slow down."),
    "TTS_FAILED": (502, True, "Narration could not be generated by any TTS provider."),
    "ALL_PROVIDERS_FAILED": (502, True, "No footage source returned usable clips and fallbacks failed."),
    "RENDER_FAILED": (500, True, "ffmpeg failed while rendering the video."),
    "NOT_FOUND": (404, False, "Route not found."),
    "INTERNAL_ERROR": (500, True, "Unexpected server error."),
}


class ApiError(Exception):
    def __init__(self, code: str, message: str | None = None, details: dict | None = None):
        status, retryable, desc = ERROR_CODES.get(code, (500, True, "Error"))
        self.code, self.status, self.retryable = code, status, retryable
        self.message = message or desc
        self.details = details or {}
        super().__init__(self.message)

    def to_dict(self) -> dict:
        return {"error": {"code": self.code, "message": self.message,
                          "retryable": self.retryable, "details": self.details}}


def install_handlers(app) -> None:
    @app.exception_handler(ApiError)
    async def _api_error(_: Request, exc: ApiError):
        return JSONResponse(exc.to_dict(), status_code=exc.status)

    @app.exception_handler(RequestValidationError)
    async def _validation(_: Request, exc: RequestValidationError):
        err = ApiError("VALIDATION_ERROR", details={"errors": [
            {"loc": list(e.get("loc", [])), "msg": e.get("msg")} for e in exc.errors()]})
        return JSONResponse(err.to_dict(), status_code=err.status)

    @app.exception_handler(StarletteHTTPException)
    async def _http(_: Request, exc: StarletteHTTPException):
        code = "NOT_FOUND" if exc.status_code == 404 else "VALIDATION_ERROR" if exc.status_code < 500 else "INTERNAL_ERROR"
        return JSONResponse(ApiError(code, str(exc.detail)).to_dict(), status_code=exc.status_code)

    @app.exception_handler(Exception)
    async def _unhandled(_: Request, exc: Exception):
        return JSONResponse(ApiError("INTERNAL_ERROR", "Unexpected server error.",
                                     {"type": type(exc).__name__}).to_dict(), status_code=500)
